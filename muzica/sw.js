/* Cadru Muzică: funcționează și fără internet după prima deschidere.
   Sample-urile instrumentelor se păstrează în cache; pagina se ia de pe net când există. */
const C = 'cadru-muzica-v2';
self.addEventListener('install', e => { self.skipWaiting(); e.waitUntil(caches.open(C).then(c => c.addAll(['./', 'index.html', 'manifest.webmanifest', 'icon.svg']))); });
self.addEventListener('activate', e => e.waitUntil(caches.keys().then(ks => Promise.all(ks.filter(k => k !== C).map(k => caches.delete(k)))).then(() => self.clients.claim())));
self.addEventListener('fetch', e => {
  const u = new URL(e.request.url);
  if (e.request.method !== 'GET') return;
  const cacheFirst = u.pathname.includes('/samples/') || u.pathname.includes('/mostre/') || u.hostname === 'cdn.jsdelivr.net';
  if (cacheFirst) {
    e.respondWith(caches.match(e.request).then(r => r || fetch(e.request).then(res => { if (res.ok) { const cp = res.clone(); caches.open(C).then(c => c.put(e.request, cp)); } return res; })));
  } else if (u.origin === location.origin) {
    e.respondWith(fetch(e.request).then(res => { if (res.ok) { const cp = res.clone(); caches.open(C).then(c => c.put(e.request, cp)); } return res; }).catch(() => caches.match(e.request)));
  }
});
