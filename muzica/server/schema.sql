CREATE TABLE IF NOT EXISTS users(
  id TEXT PRIMARY KEY,
  email TEXT UNIQUE NOT NULL,
  plan TEXT NOT NULL DEFAULT 'free',
  credits INTEGER NOT NULL DEFAULT 3,
  refill_at INTEGER NOT NULL DEFAULT 0,
  sub_id TEXT,
  created_at INTEGER NOT NULL
);
CREATE TABLE IF NOT EXISTS tokens(hash TEXT PRIMARY KEY, user_id TEXT NOT NULL, kind TEXT NOT NULL, exp INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS events(id TEXT PRIMARY KEY, created_at INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS generations(id TEXT PRIMARY KEY, user_id TEXT NOT NULL, seconds INTEGER, credits INTEGER, prompt TEXT, ok INTEGER, created_at INTEGER NOT NULL);
